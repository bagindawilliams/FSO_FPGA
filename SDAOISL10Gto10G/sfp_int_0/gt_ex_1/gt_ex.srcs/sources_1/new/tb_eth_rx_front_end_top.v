module tb_eth_rx_front_end_top();

    reg clk;
    reg rst_n;
    reg trigger;
    reg [15:0] target_frame_size;

    // AXI-Stream from Virtual PC
    wire [31:0] gen_tdata;
    wire [3:0]  gen_tkeep;
    wire        gen_tvalid, gen_tlast, gen_tready;

    // Physical XGMII Link
    wire [31:0] xgmii_txd;
    wire [3:0]  xgmii_txc;

    // FSO Output & [Rev 2.8 - Fix A18] 14-Bit Segment Valid Bytes Tracker
    wire [31:0] fso_data_out;
    wire        fso_valid, fso_last;
    reg         fso_ready;
    wire [13:0] seg_valid_bytes;

    // Instantiations
    eth_axis_packet_gen u_packet_gen (
        .clk(clk), .rst_n(rst_n), .trigger(trigger), .frame_size_bytes(target_frame_size),
        .m_axis_tdata(gen_tdata), .m_axis_tkeep(gen_tkeep),
        .m_axis_tvalid(gen_tvalid), .m_axis_tlast(gen_tlast), .m_axis_tready(gen_tready)
    );

    xgmii_tx_encoder u_tx_encoder (
        .clk(clk), .rst_n(rst_n),
        .s_axis_tdata(gen_tdata), .s_axis_tkeep(gen_tkeep),
        .s_axis_tvalid(gen_tvalid), .s_axis_tlast(gen_tlast), .s_axis_tready(gen_tready),
        .xgmii_txd(xgmii_txd), .xgmii_txc(xgmii_txc)
    );

    eth_rx_front_end_top #(.RUN_MODE(1)) u_front_end_dut (
        .clk(clk), .rst_n(rst_n),
        .xgmii_rxd(xgmii_txd), .xgmii_rxc(xgmii_txc),
        .fso_data_out(fso_data_out), .fso_valid(fso_valid), .fso_last(fso_last), .fso_ready(fso_ready),
        .seg_valid_bytes(seg_valid_bytes),
        .refclk_p(1'b0), .refclk_n(1'b0), .reset(1'b0), .dclk(1'b0), .rxp(1'b0), .rxn(1'b0)
    );

    // Clock Generation 312.5 MHz (3.2ns period)
    initial begin
        clk = 1'b0;
        forever #1.6 clk = ~clk; 
    end

    // Sub-cycle 0.8 ns byte stepper (1 -> 2 -> 3 -> 4 inside each 3.2 ns word clock)
    reg [2:0] sub_byte_step = 3'd1;
    always @(posedge clk) begin
        sub_byte_step <= 3'd1;
        #0.8 sub_byte_step <= 3'd2;
        #0.8 sub_byte_step <= 3'd3;
        #0.8 sub_byte_step <= 3'd4;
    end

    // Reference FIFO capturing every word generated by u_packet_gen (2 x 500 words = 1000 words)
    reg [31:0] exp_gen_fifo [0:2047];
    integer    exp_wr_ptr           = 0;
    integer    exp_rd_ptr           = 0;
    integer    data_mismatch_cnt    = 0;
    integer    padding_mismatch_cnt = 0;
    integer    last_pos_error_cnt   = 0;
    integer    len_meta_error_cnt   = 0;

    reg [15:0] raw_gen_idx          = 16'd0;
    reg [15:0] raw_xgmii_in_idx     = 16'd0;
    wire       gen_xfer_active      = gen_tvalid && gen_tready;
    wire       xgmii_in_active      = (xgmii_txc != 4'b1111);

    // Gated generator data display: 0 when handshake is not active (hides stall/idle hold)
    wire [31:0] gen_active_tdata     = gen_xfer_active ? gen_tdata : 32'd0;

    // 1. Generator Input 3-Metric Counters (0 when IDLE, 1..500 Clocks, 4..2000 Byte-Clock, 1..2000 Byte-per-Byte)
    wire [15:0] in_gen_clk_cnt       = gen_xfer_active ? (raw_gen_idx + 16'd1) : 16'd0;
    wire [15:0] in_gen_byte_clk_cnt  = gen_xfer_active ? ((raw_gen_idx + 16'd1) * 16'd4) : 16'd0;
    wire [15:0] in_gen_byte_1b_cnt   = gen_xfer_active ? ((raw_gen_idx * 16'd4) + {13'd0, sub_byte_step}) : 16'd0;

    // 2. XGMII Input 3-Metric Counters (0 when IDLE & /T/, 1..502 Clocks, 4..2008 Byte-Clock, 1..2008 Byte-per-Byte)
    wire [15:0] xgmii_in_clk_cnt      = xgmii_in_active ? (raw_xgmii_in_idx + 16'd1) : 16'd0;
    wire [15:0] xgmii_in_byte_clk_cnt = xgmii_in_active ? ((raw_xgmii_in_idx + 16'd1) * 16'd4) : 16'd0;
    wire [15:0] xgmii_in_byte_1b_cnt  = xgmii_in_active ? ((raw_xgmii_in_idx * 16'd4) + {13'd0, sub_byte_step}) : 16'd0;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            exp_wr_ptr       <= 0;
            raw_gen_idx      <= 16'd0;
            raw_xgmii_in_idx <= 16'd0;
        end else begin
            if (gen_xfer_active) begin
                exp_gen_fifo[exp_wr_ptr] <= gen_tdata;
                exp_wr_ptr               <= exp_wr_ptr + 1;
                if (gen_tlast)
                    raw_gen_idx <= 16'd0;
                else
                    raw_gen_idx <= raw_gen_idx + 16'd1;
            end else begin
                raw_gen_idx <= 16'd0;
            end

            if (xgmii_in_active)
                raw_xgmii_in_idx <= raw_xgmii_in_idx + 16'd1;
            else
                raw_xgmii_in_idx <= 16'd0;
        end
    end
    
    // =========================================================================
    // 3. SEGMENTED FSO OUTPUT & ZERO-LAG 1..4 SEGMENT / TAG / FCS TRACKERS
    // =========================================================================
    reg  [15:0] payload_cycle_cnt  = 16'd0;
    integer     raw_seg_idx        = 0;     // 0..3 during Segments 1..4, 4 after completion
    integer     total_tag_ok_q     = 0;
    integer     total_fcs_ok_q     = 0;
    reg  [31:0] tag_w9_q           = 32'd0; // Latches "Kook" (0x4B6F6F6B)
    reg  [31:0] tag_w10_q          = 32'd0; // Latches "min " (0x6D696E20)
    reg  [95:0] captured_tag_q     = 96'd0;

    wire        seg_out_active     = fso_valid && fso_ready;
    wire        is_cont_segment    = (raw_seg_idx == 1) || (raw_seg_idx == 3);
    wire [13:0] exp_end_seg_bytes  = is_cont_segment ? 14'd100 : 14'd1900;

    // Zero-lag detection on the exact clock cycle of "FSO " (cycle 12) and 0xDEADBEEF (cycle 25)
    wire        tag_w9_now         = seg_out_active && (!is_cont_segment) && (payload_cycle_cnt == 16'd9);
    wire        tag_w10_now        = seg_out_active && (!is_cont_segment) && (payload_cycle_cnt == 16'd10);
    wire        tag_w11_now        = seg_out_active && (!is_cont_segment) && (payload_cycle_cnt == 16'd11);
    wire        tag_hit_now        = tag_w11_now && ({tag_w9_q, tag_w10_q, fso_data_out} == 96'h4B6F_6F6B_6D69_6E20_4653_4F20);
    wire        fcs_hit_now        = seg_out_active && is_cont_segment && (payload_cycle_cnt == 16'd24) && (fso_data_out == 32'hDEAD_BEEF);

    // Zero-Lag Waveform Signals (0 when IDLE; active 1..4 for segments, immediate update on cycle 12 & cycle 25!)
    wire [31:0] completed_seg_cnt  = seg_out_active ? (raw_seg_idx + 1) : 32'd0;
    wire [31:0] kookmin_tag_ok_cnt = seg_out_active ? (total_tag_ok_q + (tag_hit_now ? 1 : 0)) : 32'd0;
    wire [31:0] fcs_verified_cnt   = seg_out_active ? (total_fcs_ok_q + (fcs_hit_now ? 1 : 0)) : 32'd0;
    wire [95:0] captured_ascii_tag = !seg_out_active ? 96'd0 :
                                     tag_w9_now      ? {fso_data_out, 64'd0} :
                                     tag_w10_now     ? {tag_w9_q, fso_data_out, 32'd0} :
                                     tag_w11_now     ? {tag_w9_q, tag_w10_q, fso_data_out} :
                                                       captured_tag_q;

    // 3-Metric Segmented FSO Output Counters (0 when IDLE, 1..475 Clocks, 4..1900 Byte-Clock, 1..1900 Byte-per-Byte)
    wire [9:0]  seg_out_clk_cnt      = seg_out_active ? (payload_cycle_cnt[9:0] + 10'd1) : 10'd0;
    wire [11:0] seg_out_byte_cnt     = seg_out_active ? ({2'd0, seg_out_clk_cnt} * 12'd4) : 12'd0;
    wire [11:0] seg_out_byte_clk_cnt = seg_out_byte_cnt;
    wire [11:0] seg_out_byte_1b_cnt  = seg_out_active ? ((payload_cycle_cnt[11:0] * 12'd4) + {9'd0, sub_byte_step}) : 12'd0;

    // Clean Active Ethernet Byte Counter inside Segment (0 when IDLE; 4..1900 on Seg 1/3; 4..100 held at 100 on Seg 2/4)
    wire [13:0] seg_valid_bytes_clean = !seg_out_active ? 14'd0 :
                                        (is_cont_segment && (payload_cycle_cnt >= 16'd25)) ? 14'd100 :
                                        ({2'd0, seg_out_byte_clk_cnt});

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            payload_cycle_cnt    <= 16'd0;
            raw_seg_idx          <= 0;
            total_tag_ok_q       <= 0;
            total_fcs_ok_q       <= 0;
            tag_w9_q             <= 32'd0;
            tag_w10_q            <= 32'd0;
            captured_tag_q       <= 96'd0;
            exp_rd_ptr           <= 0;
            data_mismatch_cnt    <= 0;
            padding_mismatch_cnt <= 0;
            last_pos_error_cnt   <= 0;
            len_meta_error_cnt   <= 0;
        end else if (fso_valid && fso_ready) begin
            // 1. Check active data words vs. zero-padding words
            if (!is_cont_segment || (payload_cycle_cnt < 16'd25)) begin
                if (fso_data_out !== exp_gen_fifo[exp_rd_ptr]) begin
                    data_mismatch_cnt <= data_mismatch_cnt + 1;
                end
                exp_rd_ptr <= exp_rd_ptr + 1;
            end else begin
                if (fso_data_out !== 32'd0) begin
                    padding_mismatch_cnt <= padding_mismatch_cnt + 1;
                end
            end

            // 2. Latch 'Kookmin FSO ' ASCII signature (Start Segments 1 & 3) & 2000th-Byte FCS
            if (!is_cont_segment) begin
                if (payload_cycle_cnt == 16'd9) begin
                    tag_w9_q       <= fso_data_out;
                    captured_tag_q <= {fso_data_out, 64'd0};
                end
                if (payload_cycle_cnt == 16'd10) begin
                    tag_w10_q      <= fso_data_out;
                    captured_tag_q <= {tag_w9_q, fso_data_out, 32'd0};
                end
                if (payload_cycle_cnt == 16'd11) begin
                    captured_tag_q <= {tag_w9_q, tag_w10_q, fso_data_out};
                    if ({tag_w9_q, tag_w10_q, fso_data_out} == 96'h4B6F_6F6B_6D69_6E20_4653_4F20)
                        total_tag_ok_q <= total_tag_ok_q + 1;
                end
            end
            if (is_cont_segment && (payload_cycle_cnt == 16'd24) && (fso_data_out == 32'hDEAD_BEEF)) begin
                total_fcs_ok_q <= total_fcs_ok_q + 1;
            end

            // 3. Check exact fso_last position (must assert only at word index 474)
            if ((payload_cycle_cnt < 16'd474) && fso_last) begin
                last_pos_error_cnt <= last_pos_error_cnt + 1;
            end
            if ((payload_cycle_cnt == 16'd474) && !fso_last) begin
                last_pos_error_cnt <= last_pos_error_cnt + 1;
            end

            // 4. At end of segment, check final seg_valid_bytes metadata (1900, 100, 1900, 100)
            if (fso_last || (payload_cycle_cnt == 16'd474)) begin
                if (seg_valid_bytes !== exp_end_seg_bytes) begin
                    len_meta_error_cnt <= len_meta_error_cnt + 1;
                end
                $display(" [%0t] Segment %0d Completed (475 Words = 1900B) | End-of-Segment Valid Bytes (seg_valid_bytes) = %0d B",
                         $time, raw_seg_idx + 1, seg_valid_bytes);
                raw_seg_idx       <= raw_seg_idx + 1;
                payload_cycle_cnt <= 16'd0;
            end else begin
                payload_cycle_cnt <= payload_cycle_cnt + 1'b1;
            end
        end else begin
            payload_cycle_cnt <= 16'd0;
        end
    end

    // Simulation Scenario
    initial begin
        rst_n     = 1'b0;
        trigger   = 1'b0;
        fso_ready = 1'b1; // Framer is always ready
        target_frame_size = 16'd2000; // Force Jumbo Frame
        
        #100;
        rst_n = 1'b1;
        #50;
        
        $display("\n[%0t] SCENARIO: Firing TWO 2000-Byte Jumbo Frames Back-to-Back...", $time);
        
        // Fire Jumbo 1
        @(posedge clk); trigger = 1'b1; 
        @(posedge clk); trigger = 1'b0; 
        
        #1610; 
        
        // Fire Jumbo 2
        @(posedge clk); trigger = 1'b1; 
        @(posedge clk); trigger = 1'b0;
        
        #6500;
        $display("\n=======================================================");
        $display(" FRONT-END JUMBO SEGMENTATION & ELASTIC FIFO REPORT");
        $display(" -> Generator Words Captured        : %0d Words (4000 Bytes)", exp_wr_ptr);
        $display(" -> Total 475-Word Segments Emitted : %0d / 4", raw_seg_idx);
        $display(" -> 'Kookmin FSO ' Tag Verified     : %0d / 2 Jumbo Packets", total_tag_ok_q);
        $display(" -> 2000th-Byte FCS (0xDEADBEEF) OK : %0d / 2 Jumbo Packets", total_fcs_ok_q);
        $display(" -> Active Data Word Mismatches     : %0d", data_mismatch_cnt);
        $display(" -> Zero-Padding Word Mismatches    : %0d", padding_mismatch_cnt);
        $display(" -> fso_last Position Errors        : %0d", last_pos_error_cnt);
        $display(" -> End-of-Segment Metadata Errors  : %0d", len_meta_error_cnt);
        if (raw_seg_idx == 4 && total_fcs_ok_q == 2 && total_tag_ok_q == 2 &&
            exp_wr_ptr == 1000 && exp_rd_ptr == 1000 &&
            data_mismatch_cnt == 0 && padding_mismatch_cnt == 0 &&
            last_pos_error_cnt == 0 && len_meta_error_cnt == 0)
            $display(" -> RESULT: [PASS] ZERO DROPPED PACKETS & EXACT 1900B/100B SPLIT!");
        else
            $fatal(1, " -> RESULT: [FAIL] Segment count, data, padding, last, or metadata mismatch!");
        $display("=======================================================\n");
        $finish;
    end
endmodule